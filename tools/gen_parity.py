"""Generate PARITY.md: bethington/ghidra-mcp endpoint -> kawaiidra tool mapping.

Usage:
    python tools/gen_parity.py [path to bethington tests/endpoints.json]

Defaults to the vendored copy in tools/data/.

Fails (exit 1) if any competitor endpoint has no kawaiidra equivalent or maps
to a tool that does not exist, so the parity claim stays verifiable.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

# Competitor endpoint -> kawaiidra tool(s) where the names differ.
ALIASES = {
    "analyze_control_flow": ["get_control_flow_graph"],
    "detect_crypto_constants": ["find_crypto_constants"],
    "extract_iocs_with_context": ["extract_iocs"],
    "find_anti_analysis_techniques": ["find_anti_analysis"],
    "analyze_api_call_chains": ["analyze_api_chains"],
    "clear_function_comments": ["clear_comments"],
    "find_data_types": ["list_data_types", "get_valid_data_types"],
    "get_enum_values": ["get_data_type_details"],
    "get_struct_layout": ["get_data_type_details"],
    "get_type_size": ["get_data_type_details", "validate_data_type"],
    "inspect_memory_content": ["read_memory", "analyze_data_region"],
    "search_byte_patterns": ["search_bytes"],
    "disassemble_function": ["get_function_disassembly"],
    "get_function_call_graph": ["get_call_graph"],
    "get_metadata": ["get_binary_info"],
    "import_file": ["analyze_binary"],
    "reanalyze": ["run_analysis"],
    "run_script_inline": ["run_script"],
    "get_function_hash": ["get_function_hash", "get_function_hashes"],
    "set_comment": ["set_comment", "set_plate_comment", "set_pre_comment", "set_repeatable_comment"],
    "batch_set_comments": ["batch_set_comments"],
    "create_derived_type": ["create_derived_type", "create_typedef"],
    "diff_functions": ["diff_functions"],
    "list_project_files": ["list_project_files", "list_project_binaries"],
    "list_open_programs": ["list_open_programs", "list_analyzed_binaries"],
    "rename_symbol": ["rename_symbol", "rename_label", "rename_data"],
    "tool/goto_address": ["goto_address", "set_current_address"],
    "tool/running_tools": ["running_tools"],
    "mcp/health": ["mcp_health"],
    "mcp/schema": ["mcp_schema"],
    "get_ui_cursor": ["get_ui_cursor", "get_current_address", "get_current_function", "get_current_selection"],
    "bulk_fuzzy_match": ["bulk_fuzzy_match", "compare_binaries"],
}


def kawaiidra_name(endpoint: str) -> list[str]:
    if endpoint in ALIASES:
        return ALIASES[endpoint]
    return [endpoint.replace("/", "_")]


def main() -> int:
    src = sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "tools" / "data" / "bethington_endpoints.json")
    os.environ.setdefault("GHIDRA_INSTALL_DIR", str(ROOT.parent / "ghidra_12.0.3_PUBLIC"))
    from kawaiidra_mcp.parity import REGISTRY
    from kawaiidra_mcp.server import TOOLS

    tools = {t.name for t in TOOLS}
    data = json.loads(Path(src).read_text(encoding="utf-8"))
    rows, missing, used = [], [], set()
    for e in sorted(data["endpoints"], key=lambda e: (e["category"], e["path"])):
        ep = e["path"].lstrip("/")
        targets = kawaiidra_name(ep)
        absent = [t for t in targets if t not in tools]
        if absent:
            missing.append((ep, absent))
        used.update(targets)
        how = "same name" if targets == [ep] else ("renamed" if len(targets) == 1 and targets[0] == ep.replace("/", "_") else "equivalent")
        mode = "GUI bridge" if "gui" in e["servers"] and "headless" not in e["servers"] else "headless"
        rows.append(f"| `{ep}` | {e['category']} | {', '.join(f'`{t}`' for t in targets)} | {how} | {mode} |")

    extras = sorted(tools - used)
    apple = [t for t in extras if any(k in t for k in ("mach", "kpp", "pac_", "iokit", "sandbox", "entitlement", "kernel", "jni"))]
    other = [t for t in extras if t not in apple]

    out = [
        "# Feature Parity: kawaiidra vs bethington/ghidra-mcp",
        "",
        f"Generated by `tools/gen_parity.py` from bethington/ghidra-mcp `tests/endpoints.json` "
        f"(v{data.get('version', '?')}, {len(data['endpoints'])} endpoints).",
        "",
        "| Metric | Count |",
        "|--------|-------|",
        f"| Competitor endpoints | {len(data['endpoints'])} |",
        f"| Covered by kawaiidra | {len(data['endpoints']) - len(missing)} |",
        f"| Kawaiidra tools total | {len(tools)} ({len(tools) - len(REGISTRY)} core + {len(REGISTRY)} parity) |",
        f"| Kawaiidra-only tools | {len(extras)} (incl. {len(apple)} Apple/iOS/kernel/JNI) |",
        "",
        "\"GUI bridge\" endpoints are GUI-only in the competitor too; kawaiidra serves them through",
        "its GUI mode (`KAWAIIDRA_GUI_MODE=true` + ghidra_bridge server running in Ghidra).",
        "",
        "## Endpoint mapping",
        "",
        "| Competitor endpoint | Category | Kawaiidra tool(s) | Mapping | Mode |",
        "|---------------------|----------|-------------------|---------|------|",
        *rows,
        "",
        "## Kawaiidra-only tools",
        "",
        "### Apple / iOS / kernel / mobile",
        "",
        ", ".join(f"`{t}`" for t in apple),
        "",
        "### Other",
        "",
        ", ".join(f"`{t}`" for t in other),
        "",
    ]
    (ROOT / "PARITY.md").write_text("\n".join(out), encoding="utf-8")
    print(f"endpoints={len(data['endpoints'])} covered={len(data['endpoints']) - len(missing)} "
          f"tools={len(tools)} extras={len(extras)} apple={len(apple)}")
    for ep, absent in missing:
        print(f"MISSING: {ep} -> {absent}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
